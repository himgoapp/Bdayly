-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.birthday_pages (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  recipient_name text not null check (char_length(recipient_name) between 1 and 50),
  sender_name text not null default '',
  category text not null default 'Friends',
  template_id text not null default 'bestie',
  message text not null default '',
  birthday_date date,
  photo_url text,
  created_at timestamptz not null default now()
);

alter table public.birthday_pages enable row level security;

-- Public MVP: anyone can create and read a birthday page.
-- For a public launch, add rate limiting / abuse protection and consider moderation.
drop policy if exists "Anyone can create birthday pages" on public.birthday_pages;
create policy "Anyone can create birthday pages"
  on public.birthday_pages for insert
  to anon, authenticated
  with check (
    char_length(slug) between 3 and 40 and
    char_length(recipient_name) between 1 and 50 and
    char_length(message) <= 600
  );

drop policy if exists "Anyone can read birthday pages" on public.birthday_pages;
create policy "Anyone can read birthday pages"
  on public.birthday_pages for select
  to anon, authenticated
  using (true);
